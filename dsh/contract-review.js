// 黑名单命中判定：**必须排除否定/免责语境**。
// 合同里合法写明「乙方不保证中标」「本合同不含"保证中标""包过"等表述」属反承诺条款，不是承诺；
// 否则模板自带的反承诺条款会把自己判成高风险（W3 把生成文本喂回来时 100% 触发）。
// 判据：命中词紧邻左侧 60 字窗口内出现否定/排除词，且否定词到命中词之间没有句读（。；，、）或转折词（但）断开。
// 窗口要够宽：合同常用「本合同不含"保证中标""包过""确保通过"…等表述」这种枚举式反承诺，否定词会离得很远。
const NEG_WINDOW = /(不|无|非|禁止|严禁|不得|不予|不含|不包含|排除|拒绝|避免)[^。；\n，,、但]{0,50}$/
function 黑名单命中(s) {
  const str = String(s == null ? '' : s)
  const hits = []
  for (const kw of REVIEW_BLACKLIST) {
    let from = 0
    for (;;) {
      const i = str.indexOf(kw, from)
      if (i < 0) break
      if (!NEG_WINDOW.test(str.slice(Math.max(0, i - 60), i))) { hits.push(kw); break }
      from = i + kw.length
    }
  }
  return hits
}

