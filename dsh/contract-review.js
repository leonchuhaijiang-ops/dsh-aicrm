/* ============================== 输入归一化 ============================== */
function isBlank(v) {
  if (v === null || v === undefined) return true
  if (Array.isArray(v)) return v.length === 0
  if (typeof v === 'string') {
    const s = v.trim()
    return s === '' || /^\{\{[^}]*\}\}$/.test(s) || /^【[^】]*】$/.test(s) || /^[＿_\-—]{2,}$/.test(s)
  }
  return false
}

function fmt(v) {
  if (Array.isArray(v)) return v.map((x) => (x && typeof x === 'object' ? Object.values(x).join(' ') : String(x))).join('；')
  if (v && typeof v === 'object') return Object.values(v).join(' ')
  return String(v)
}

const RESERVED = new Set(['text', '正文', '合同文本', '文本', 'content', 'fields', 'data', '合同', 'meta'])

function normalize(input) {
  if (typeof input === 'string') return { text: input, fields: {}, meta: {} }
  const raw = input && typeof input === 'object' ? input : {}
  const text = String(raw.text || raw.正文 || raw.合同文本 || raw.文本 || raw.content || '')
  const fields = {}
  for (const src of [raw.fields, raw.data, raw.合同]) {
    if (src && typeof src === 'object' && !Array.isArray(src)) Object.assign(fields, src)
  }
  for (const k of Object.keys(raw)) if (!RESERVED.has(k)) fields[k] = raw[k]
  const meta = raw.meta && typeof raw.meta === 'object' ? raw.meta : {}
  return { text, fields, meta }
}

function valOf(fields, ...names) {
  for (const n of names) if (!isBlank(fields[n])) return fields[n]
  return undefined
}

/* ============================== 数值 / 日期 ============================== */
function amountOf(v) {
  if (typeof v === 'number') return Number.isFinite(v) ? v : NaN
  const s = String(v == null ? '' : v).replace(/[,，\s]/g, '')
  const m = s.match(/(-?\d+(?:\.\d+)?)\s*(万元|万|元)?/)
  if (!m) return NaN
  let n = Number(m[1])
  if (m[2] === '万元' || m[2] === '万') n *= 10000
  return n
}

function pctOf(v) {
  if (typeof v === 'number') return Number.isFinite(v) ? (v > 0 && v <= 1 ? v * 100 : v) : NaN
  const s = String(v == null ? '' : v)
  const m = s.match(/(\d+(?:\.\d+)?)\s*[%％]/)
  if (m) return Number(m[1])
  const m2 = s.match(/^(\d+(?:\.\d+)?)$/)
  if (m2) { const n = Number(m2[1]); return n > 0 && n <= 1 ? n * 100 : n }
  return NaN
}

function dateOf(v) {
  const s = String(v == null ? '' : v)
  let m = s.match(/(\d{4})\s*[-/.年]\s*(\d{1,2})\s*[-/.月]\s*(\d{1,2})/)
  if (m) return new Date(Number(m[1]), Number(m[2]) - 1, Number(m[3]))
  m = s.match(/(\d{4})\s*[-/.年]\s*(\d{1,2})/)
  if (m) return new Date(Number(m[1]), Number(m[2]) - 1, 1)
  return null
}

function paymentNodes(fields) {
  const raw = valOf(fields, '付款节点', '付款计划', '付款安排')
  if (!Array.isArray(raw)) return []
  return raw.map((item) => {
    if (Array.isArray(item)) return { 名称: item[0], 比例: item[1], 触发: item[3] }
    if (item && typeof item === 'object') {
      return { 名称: item['节点'] ?? item['名称'], 比例: item['付款比例'] ?? item['比例'], 触发: item['触发条件'] ?? item['条件'] }
    }
    return {}
  })
}

